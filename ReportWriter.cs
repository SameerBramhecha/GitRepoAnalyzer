namespace RepoAnalyzer.Core;

public static class ReportWriter
{
    /// <summary>
    /// Write the analysis output to the reports directory inside the repo.
    /// Returns the absolute paths of all written files (for git staging).
    /// </summary>
    public static async Task<List<string>> WriteAsync(
        string         repoPath,
        AnalysisResult result,
        InstructionSet instructions,
        AnalysisOptions options)
    {
var outputDir = Path.IsPathRooted(options.OutputDirectory)
    ? options.OutputDirectory
    : Path.Combine(repoPath, options.OutputDirectory);
        Directory.CreateDirectory(outputDir);

        // Write the main analysis report
        var reportPath = Path.Combine(outputDir, instructions.ReportFileName);
        await File.WriteAllTextAsync(reportPath, BuildMarkdown(result, instructions));
        Console.WriteLine($"\n📄  Report written → {Path.GetRelativePath(repoPath, reportPath)}");

        // Write/update the index file that lists all past reports
        var indexPath = Path.Combine(outputDir, "README.md");
        await UpdateIndexAsync(indexPath, instructions.ReportFileName, result);

        return [reportPath, indexPath];
    }

    // ── Markdown document ──────────────────────────────────────────────────

    private static string BuildMarkdown(AnalysisResult result, InstructionSet instructions)
    {
        return $"""
            # {instructions.Name}

            | | |
            |---|---|
            | **Repository** | {result.RepoUrl} |
            | **Analysis date** | {result.Timestamp:yyyy-MM-dd HH:mm} UTC |
            | **Instruction set** | `{result.InstructionSetName}` |
            | **Model** | `{result.ModelUsed}` |

            ---

            {result.Content}

            ---

            *Generated automatically by [RepoAnalyzer](https://github.com/your-org/repo-analyzer)*
            """;
    }

    // ── Reports index ──────────────────────────────────────────────────────

    private static async Task UpdateIndexAsync(string indexPath, string reportFile, AnalysisResult result)
    {
        const string header = "# Analysis reports\n\nAuto-generated by RepoAnalyzer.\n\n| Date | Report | Instruction set |\n|---|---|---|\n";

        var newRow = $"| {result.Timestamp:yyyy-MM-dd HH:mm} UTC " +
                     $"| [{reportFile}](./{reportFile}) " +
                     $"| `{result.InstructionSetName}` |\n";

        string existing = File.Exists(indexPath) ? await File.ReadAllTextAsync(indexPath) : header;

        // Insert new row after the table header if it's already there, else rebuild
        var content = existing.Contains("| Date |")
            ? existing.Replace("| Date | Report | Instruction set |\n|---|---|---|\n",
                               "| Date | Report | Instruction set |\n|---|---|---|\n" + newRow)
            : header + newRow;

        await File.WriteAllTextAsync(indexPath, content);
    }
}
